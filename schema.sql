CREATE TABLE IF NOT EXISTS invitations (
 id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 token_hash text NOT NULL UNIQUE,
 first_name text NOT NULL, last_name text NOT NULL,
 role text NOT NULL CHECK (role IN ('admin','user')),
 camera_ids integer[] NOT NULL DEFAULT '{}',
 group_ids integer[] NOT NULL DEFAULT '{}',
 creator_id bigint NOT NULL REFERENCES users(id),
 used_by bigint REFERENCES users(id), revoked boolean NOT NULL DEFAULT false,
 created_at timestamptz NOT NULL DEFAULT now(), expires_at timestamptz NOT NULL DEFAULT now()+interval '7 days'
);
CREATE TABLE IF NOT EXISTS sessions (
 token_hash text PRIMARY KEY, user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 csrf text NOT NULL, expires_at timestamptz NOT NULL DEFAULT now()+interval '12 hours'
);
CREATE TABLE IF NOT EXISTS layouts (
 user_id bigint PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
 value jsonb NOT NULL, updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS settings (key text PRIMARY KEY, value text NOT NULL);
