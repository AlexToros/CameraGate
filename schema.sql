CREATE TABLE IF NOT EXISTS users (
 id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 login text NOT NULL UNIQUE, password_hash text NOT NULL,
 first_name text NOT NULL, last_name text NOT NULL,
 role text NOT NULL CHECK (role IN ('admin','user')),
 blocked boolean NOT NULL DEFAULT false,
 camera_ids integer[] NOT NULL DEFAULT '{}',
 group_ids integer[] NOT NULL DEFAULT '{}',
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS cameras (
 id integer PRIMARY KEY CHECK (id BETWEEN 1 AND 256),
 source_name text NOT NULL, display_name text NOT NULL, active boolean NOT NULL DEFAULT true
);
CREATE TABLE IF NOT EXISTS camera_groups (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name text NOT NULL UNIQUE, camera_ids integer[] NOT NULL DEFAULT '{}',
 builtin boolean NOT NULL DEFAULT false
);
